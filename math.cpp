#include <iostream>
#include <cmath>

using namespace std;

int main(){
    float n = 6.5;
    
    cout << " round to the nearest integers " << round(n) << endl;
    cout << " round up " << ceil(n) << endl;
    cout << " round down " << floor(n) << endl;
    cout << " the valuer of n is equal to " << n << endl;
    
    return 0;
}
